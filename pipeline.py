#!/usr/bin/env python3
"""One-command pipeline, preserving human approvals for sources/science/publishing."""
import argparse
import subprocess
import sys
from pathlib import Path

from voiceover import normalize_rate_args

ROOT = Path(__file__).resolve().parent


def step(*args):
    print("\n==>", " ".join(map(str, args)), flush=True)
    subprocess.run([sys.executable, *map(str, args)], cwd=ROOT, check=True)


def main():
    ap = argparse.ArgumentParser(description="GE1013: only real USGS footage, free Edge TTS")
    ap.add_argument("stage", choices=["prepare", "render", "all"])
    ap.add_argument("--assignment-pdf", type=Path)
    ap.add_argument("--no-tts", action="store_true", help="Use a manually supplied voiceover instead of free Edge TTS")
    ap.add_argument("--voice", default=None, help="Optional language-compatible Edge TTS voice")
    ap.add_argument("--rate", default="+0%", help="TTS speech rate, e.g. -5%, +5%")
    ap.add_argument("--force-tts", action="store_true", help="Regenerate voice if source script changed")
    ap.add_argument("--no-subtitles", action="store_true", help="Skip autogenerated subtitle burn-in")
    args = ap.parse_args(normalize_rate_args(sys.argv[1:]))
    if args.stage in {"prepare", "all"}:
        step("validate.py")
        step("download_assets.py")
        if args.assignment_pdf:
            step("extract_logos.py", args.assignment_pdf.resolve())
        if not args.no_tts:
            tts_args = ["voiceover.py", "--rate=" + args.rate]  # "=" keeps "-5%" from parsing as a flag
            if args.voice:
                tts_args.extend(["--voice", args.voice])
            if args.force_tts:
                tts_args.append("--force")
            step(*tts_args)
        if not args.no_subtitles:
            if args.no_tts:
                print("SKIPPING caption generation: recorded voice must be manually aligned.")
            else:
                step("subtitles.py")
        print("\nPREPARATION DONE. HUMAN SOURCE/SCIENCE/LOGO APPROVAL IS STILL REQUIRED.")
    if args.stage in {"render", "all"}:
        step("validate.py", "--strict")
        cmd = ["build.py"]
        if args.no_subtitles:
            cmd.append("--no-subtitles")
        step(*cmd)
        step("qa.py")
        print("\nTECHNICAL DRAFT COMPLETE. Watch/listen and approve before submitting.")


if __name__ == "__main__":
    main()
